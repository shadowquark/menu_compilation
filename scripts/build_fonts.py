#!/usr/bin/env python3
"""mdBook preprocessor: generate cached, versioned WOFF2 font subsets."""
from __future__ import annotations

from dataclasses import dataclass
import hashlib
from html import unescape
from html.parser import HTMLParser
from importlib.metadata import PackageNotFoundError, version
from io import BytesIO
import json
import logging
import os
from pathlib import Path
import re
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
ASSETS = Path("src/assets")
OUTPUT = ASSETS / "fonts"
CSS = ASSETS / "fonts.css"
ASCII = set(range(32, 127))


@dataclass(frozen=True)
class FontSpec:
    role: str
    family: str
    filename: str


FONTS = (
    FontSpec("body", "yu", "FZXSSK.ttf"),
    FontSpec("heading", "yuHead", "HanliOldstyle.ttf"),
    FontSpec("directory", "yuSide", "qiji-fallback.ttf"),
)


def dependencies():
    expected = dict(line.split("==", 1) for line in
                    (ROOT / "requirements-fonts.txt").read_text().splitlines() if line.strip())
    try:
        actual = {name: version(name) for name in expected}
    except PackageNotFoundError as error:
        raise RuntimeError("Install requirements-fonts.txt or run bash scripts/preview.sh") from error
    if actual != expected:
        raise RuntimeError("Font dependency versions differ; install requirements-fonts.txt or run bash scripts/preview.sh")
    return actual


def chapters(book):
    def walk(items):
        for item in items:
            if not isinstance(item, dict):
                continue
            chapter = item.get("Chapter")
            if chapter:
                yield chapter
                yield from walk(chapter.get("sub_items", []))
    yield from walk(book.get("items", book.get("sections", [])))


class HTMLHeadings(HTMLParser):
    def __init__(self, text):
        super().__init__(convert_charrefs=True)
        self.level = 0
        self.text = ""
        self.headings = []
        self.feed(text)

    def handle_starttag(self, tag, attrs):
        if tag in ("h1", "h2", "h3", "h4"):
            self.level = int(tag[1])
            self.text = ""

    def handle_data(self, data):
        if self.level:
            self.text += data

    def handle_endtag(self, tag):
        if tag == f"h{self.level}":
            self.headings.append((self.level, self.text))
            self.level = 0


def codepoints(text):
    return {ord(char) for char in unescape(text) if ord(char) >= 32 and ord(char) != 127}


def collect_characters(book, title, ui_text=""):
    # Printable ASCII also covers native mdBook dialogs and dynamically generated numbers.
    common = ASCII | codepoints(ui_text)
    sets = {role: set(common) for role in ("body", "heading", "directory")}
    sets["heading"].update(codepoints(title + "食单集注"))
    contents = list(chapters(book))
    if not contents:
        raise ValueError("No chapters found in the mdBook preprocessor input")
    for chapter in contents:
        text = chapter.get("content", "")
        sets["body"].update(codepoints(text))
        sets["directory"].update(codepoints(chapter.get("name", "")))
        # Conservative extraction retains markup characters rather than omitting visible text.
        for match in re.finditer(r"(?m)^ {0,3}(#{1,4})[ \t]+([^\n]+)", text):
            sets["heading"].update(codepoints(match[2]))
            if len(match[1]) == 2:
                sets["directory"].update(codepoints(match[2]))
        for match in re.finditer(r"(?m)^([^\n]+)\n {0,3}(=+|-+)[ \t]*$", text):
            sets["heading"].update(codepoints(match[1]))
            if match[2].startswith("-"):
                sets["directory"].update(codepoints(match[1]))
        for level, heading in HTMLHeadings(text).headings:
            sets["heading"].update(codepoints(heading))
            if level == 2:
                sets["directory"].update(codepoints(heading))
    return sets


def digest(data):
    return hashlib.sha256(data).hexdigest()


def write_changed(path, data):
    if path.exists() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as handle:
        temporary = Path(handle.name)
        handle.write(data)
    os.replace(temporary, path)


def render_css(fonts):
    rules = ["/* Generated by scripts/build_fonts.py; do not edit. */"]
    for font in fonts:
        rules.append(
            "@font-face {\n"
            f"    font-family: '{font['family']}';\n"
            "    src: url('{{ resource \"assets/fonts/" + font["file"] + "\" }}') format('woff2');\n"
            "    font-display: block;\n"
            "}\n"
        )
    return ("\n".join(rules)).encode()


def generate_fonts(book, title, root=ROOT, specs=FONTS):
    engines = dependencies()
    from fontTools import subset
    from fontTools.ttLib import TTFont

    ui_path = root / ASSETS / "navigation.js"
    ui_text = ui_path.read_text() if ui_path.exists() else ""
    # UI strings may be inserted after Markdown rendering. CJK literals cover those additions.
    ui_text = "".join(re.findall(r"[\u3000-\u9fff\uff00-\uffef]", ui_text))
    needed = collect_characters(book, title, ui_text)
    output = root / OUTPUT
    manifest_path = output / "manifest.json"
    try:
        previous = json.loads(manifest_path.read_text())
    except (OSError, ValueError):
        previous = {}
    cached = {font["family"]: font for font in previous.get("fonts", [])}
    generator = digest(Path(__file__).read_bytes())
    results, rebuilt = [], 0
    logging.getLogger("fontTools.subset").setLevel(logging.ERROR)
    for spec in specs:
        source = root / "fonts" / spec.filename
        source_bytes = source.read_bytes()
        with TTFont(source, recalcTimestamp=False) as original:
            supported = set(original.getBestCmap())
        used = sorted(needed[spec.role] & supported)
        source_hash = digest(source_bytes)
        key = digest(json.dumps([source_hash, used, engines, generator], sort_keys=True).encode())
        old = cached.get(spec.family, {})
        old_path = output / old.get("file", "missing")
        hit = (old.get("key") == key and old_path.is_file()
               and digest(old_path.read_bytes()) == old.get("sha256"))
        if hit:
            filename, raw = old["file"], old_path.read_bytes()
        else:
            # Preserve legacy glyph bounds as well as outlines: Qiji includes bounds
            # that differ slightly from recalculated values, affecting side bearings.
            with TTFont(source, recalcTimestamp=False, recalcBBoxes=False) as font:
                options = subset.Options()
                options.hinting = True
                options.layout_features = ["*"]
                options.name_IDs = ["*"]
                options.notdef_outline = True
                processor = subset.Subsetter(options=options)
                processor.populate(unicodes=used)
                processor.subset(font)
                font.flavor = "woff2"
                buffer = BytesIO()
                font.save(buffer)
                raw = buffer.getvalue()
            filename = f"{Path(spec.filename).stem}.{digest(raw)[:12]}.woff2"
            write_changed(output / filename, raw)
            rebuilt += 1
        with TTFont(output / filename) as generated:
            if not set(used) <= set(generated.getBestCmap()):
                raise ValueError(f"Subset lost supported characters: {spec.filename}")
        results.append({
            "family": spec.family, "role": spec.role, "source": f"fonts/{spec.filename}",
            "source_sha256": source_hash, "source_bytes": len(source_bytes),
            "file": filename, "sha256": digest(raw), "bytes": len(raw), "key": key,
            "codepoints": used, "missing_in_source": sorted(needed[spec.role] - supported),
        })
    manifest = {"version": 1, "generator": generator, "engines": engines, "fonts": results}
    write_changed(root / CSS, render_css(results))
    write_changed(manifest_path, (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode())
    for spec in specs:
        pattern = re.compile(re.escape(Path(spec.filename).stem) + r"\.[a-f0-9]{12}\.woff2$")
        keep = {font["file"] for font in results}
        for path in output.glob("*.woff2"):
            if pattern.fullmatch(path.name) and path.name not in keep:
                path.unlink()
    print(f"Fonts: {sum(font['source_bytes'] for font in results):,} -> "
          f"{sum(font['bytes'] for font in results):,} bytes; rebuilt {rebuilt}/{len(results)}.", file=sys.stderr)
    return manifest


def validate_fonts(root=ROOT, specs=FONTS):
    from fontTools.ttLib import TTFont
    manifest = json.loads((root / OUTPUT / "manifest.json").read_text())
    expected = {(spec.family, spec.role, f"fonts/{spec.filename}") for spec in specs}
    actual = {(font["family"], font["role"], font["source"]) for font in manifest["fonts"]}
    if actual != expected or len(manifest["fonts"]) != len(specs):
        raise ValueError("Generated font manifest does not contain the expected font families")
    if manifest["generator"] != digest(Path(__file__).read_bytes()):
        raise ValueError("Font generator changed; rebuild the book")
    for font in manifest["fonts"]:
        path = root / OUTPUT / font["file"]
        if digest(path.read_bytes()) != font["sha256"]:
            raise ValueError(f"Corrupt generated font: {path}")
        if digest((root / font["source"]).read_bytes()) != font["source_sha256"]:
            raise ValueError(f"Original font changed: {font['source']}")
        with TTFont(path) as generated:
            if generated.flavor != "woff2" or not set(font["codepoints"]) <= set(generated.getBestCmap()):
                raise ValueError(f"Incomplete font subset: {path}")
    if (root / CSS).read_bytes() != render_css(manifest["fonts"]):
        raise ValueError("Generated font CSS is stale")
    return manifest


def main():
    args = sys.argv[1:]
    if args[:1] == ["supports"]:
        raise SystemExit(0 if args[1:] == ["html"] else 1)
    if args == ["--check-dependencies"]:
        dependencies()
        return
    if args == ["--check"]:
        result = validate_fonts()
        print(f"Validated {len(result['fonts'])} WOFF2 subsets and their character coverage.")
        return
    if args:
        raise ValueError(f"Unknown arguments: {args}")
    context, book = json.load(sys.stdin)
    generate_fonts(book, context.get("config", {}).get("book", {}).get("title", ""),
                   root=Path(context.get("root", ROOT)))
    json.dump(book, sys.stdout, ensure_ascii=False)


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(f"Font build failed: {error}", file=sys.stderr)
        raise SystemExit(1)
